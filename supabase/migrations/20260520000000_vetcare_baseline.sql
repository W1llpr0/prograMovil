-- VetCare reproducible baseline.
-- This migration intentionally precedes the historical fix migrations so a
-- brand-new Supabase project can be created from this repository alone.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  first_name text not null default '',
  last_name text not null default '',
  phone text,
  document text,
  address text,
  profile_picture text,
  latitude double precision,
  longitude double precision,
  role text not null default 'client' check (role in ('client', 'veterinarian')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.veterinarians (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users(id) on delete cascade,
  license_number text unique,
  years_experience integer not null default 0 check (years_experience >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.specialties (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  is_active boolean not null default true
);

create table if not exists public.veterinarian_specialties (
  veterinarian_id uuid not null references public.veterinarians(id) on delete cascade,
  specialty_id bigint not null references public.specialties(id) on delete cascade,
  primary key (veterinarian_id, specialty_id)
);

create table if not exists public.veterinarian_availability (
  id bigint generated by default as identity primary key,
  veterinarian_id uuid not null references public.veterinarians(id) on delete cascade,
  day_of_week integer not null check (day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null,
  slot_duration_minutes integer not null default 30 check (slot_duration_minutes between 10 and 240),
  is_active boolean not null default true,
  constraint veterinarian_availability_time_check check (start_time < end_time),
  constraint uq_vet_availability_vet_day unique (veterinarian_id, day_of_week)
);

create table if not exists public.species (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_exotic boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.breeds (
  id bigint generated by default as identity primary key,
  name text not null,
  species_id bigint not null references public.species(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name, species_id)
);

create table if not exists public.pets (
  id bigint generated by default as identity primary key,
  client_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 80),
  species_id bigint not null references public.species(id),
  breed_id bigint references public.breeds(id) on delete set null,
  sex_code char(1) check (sex_code in ('M', 'F')),
  birth_date date check (birth_date is null or birth_date <= current_date),
  weight_kg numeric(8,3) check (weight_kg is null or weight_kg > 0),
  microchip text unique,
  photo_url text,
  allergies text,
  is_exotic boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.consultations (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  veterinarian_id uuid not null references public.veterinarians(id),
  specialty_id bigint references public.specialties(id),
  scheduled_at timestamptz not null,
  reason text,
  diagnosis text,
  treatment text,
  notes text,
  vitals jsonb not null default '{}'::jsonb,
  status text not null default 'pending'
    check (status in ('pending', 'scheduled', 'confirmed', 'in_progress', 'completed', 'cancelled')),
  is_contagious boolean not null default false,
  integrity_hash text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_active_vet_slot
