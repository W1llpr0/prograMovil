create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array['users','veterinarians','species','breeds','pets','consultations','epidemiological_alerts','reviews']
  loop
    execute format('drop trigger if exists trg_%I_updated_at on public.%I', table_name, table_name);
    execute format('create trigger trg_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name, table_name);
  end loop;
end $$;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_role text := case when new.raw_user_meta_data->>'role' = 'veterinarian'
    then 'veterinarian' else 'client' end;
  created_vet_id uuid;
  general_specialty_id bigint;
begin
  insert into public.users (
    id, email, first_name, last_name, phone, document, address, role
  ) values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'first_name', ''),
    coalesce(new.raw_user_meta_data->>'last_name', ''),
    nullif(new.raw_user_meta_data->>'phone', ''),
    nullif(new.raw_user_meta_data->>'document', ''),
    nullif(new.raw_user_meta_data->>'address', ''),
    requested_role
  ) on conflict (id) do update set
    email = excluded.email,
    first_name = excluded.first_name,
    last_name = excluded.last_name,
    phone = coalesce(excluded.phone, public.users.phone),
    document = coalesce(excluded.document, public.users.document),
    address = coalesce(excluded.address, public.users.address),
    role = excluded.role;

  if requested_role = 'veterinarian' then
    insert into public.veterinarians (user_id, license_number)
    values (new.id, nullif(new.raw_user_meta_data->>'document', ''))
    on conflict (user_id) do update
      set license_number = coalesce(excluded.license_number, public.veterinarians.license_number);
    select id into created_vet_id from public.veterinarians where user_id = new.id;
    select id into general_specialty_id from public.specialties where name = 'Medicina General';
    if general_specialty_id is not null then
      insert into public.veterinarian_specialties (veterinarian_id, specialty_id)
      values (created_vet_id, general_specialty_id)
      on conflict do nothing;
    end if;
    insert into public.veterinarian_availability (
      veterinarian_id, day_of_week, start_time, end_time, slot_duration_minutes, is_active
    )
    select created_vet_id, day_number, '09:00'::time, '18:00'::time, 30, true
    from generate_series(1, 6) as day_number
    on conflict (veterinarian_id, day_of_week) do nothing;
  else
    insert into public.clients (user_id) values (new.id)
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of raw_user_meta_data, email on auth.users
  for each row execute function public.handle_new_auth_user();

create or replace function public.is_veterinarian()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.veterinarians where user_id = auth.uid() and is_active);
$$;

create or replace function public.owns_pet(p_pet_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.pets where id = p_pet_id and client_id = auth.uid());
$$;

create or replace function public.can_access_consultation(p_consultation_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(
    select 1
    from public.consultations c
    join public.pets p on p.id = c.pet_id
    join public.veterinarians v on v.id = c.veterinarian_id
    where c.id = p_consultation_id
      and (p.client_id = auth.uid() or v.user_id = auth.uid())
  );
$$;

